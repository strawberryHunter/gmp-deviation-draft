"""Record what the CLI (devdraft) gives, as the reference the web app is tested against.

    python web/tools/make_fixtures.py           write the files below
    python web/tools/make_fixtures.py --check   fail if they are not what the CLI gives today (CI runs this)

Files (all generated, do not edit by hand):
    web/tests/fixtures/forms.json         the 8 synthetic forms as the CLI's form loader reads them
    web/tests/fixtures/cli_expected.json  CLI result per form: rejected, or grade / reasons / recurrence ids
    web/tests/fixtures/yaml_cases.json    YAML texts with what the CLI's form loader reads from each
    web/tests/fixtures/rules.json         config/rules.yaml as the CLI reads it, with the file's SHA-256 (what a draft records)
    web/src/sample.js                     the same forms + synthetic history + template guidance, bundled into the page
"""
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]   # web/
REPO = HERE.parent
CHECK = "--check" in sys.argv[1:]
sys.path.insert(0, str(REPO))
import yaml  # noqa: E402
from devdraft.intake import _template_comments, _template_phrases  # noqa: E402
from devdraft.rules import form_load, load_rules  # noqa: E402

TODAY = "2026-11-24"
TEXT = ["id", "title", "site", "area", "product", "batch", "equipment_id", "category", "detected_at",
        "detected_by", "process_step", "description", "immediate_actions"]
FLAGS = ["cpp_excursion", "spec_oos", "other_batches_possibly_affected", "sterility_assurance_impacted",
         "released_product_affected", "data_integrity_concern", "patient_safety_impact", "regulatory_report_required"]

paths = sorted((REPO / "data/synthetic/intake").glob("*.yaml")) + sorted((REPO / "data/synthetic/showcase").glob("*.yaml"))
assert len(paths) == 8, f"expected 8 synthetic forms, found {len(paths)}"

forms, expected = [], {}
for p in paths:
    raw = form_load(p.read_text(encoding="utf-8"))
    form = {"synthetic": raw.get("synthetic") is True, "today": TODAY,
            "flags": {k: (raw.get(k) if isinstance(raw.get(k), bool) else None) for k in FLAGS},
            "parameters": [{k: "" if x.get(k) is None else str(x.get(k)) for k in ("name", "spec", "actual", "duration")}
                           for x in (raw.get("parameters") or [])]}
    for k in TEXT:
        v = raw.get(k)
        form[k] = "" if v is None else str(v)
    forms.append({"file": p.name, "form": form})

    with tempfile.TemporaryDirectory() as out:
        r = subprocess.run([sys.executable, "-m", "devdraft.cli", str(p), "--today", TODAY, "--out", out],
                           cwd=REPO, capture_output=True, text=True, encoding="utf-8")
        mds = list(Path(out).glob("*_draft.md"))
        if r.returncode not in (0, 1):
            sys.exit(f"CLI failed on {p.name}: exit {r.returncode}\n{r.stdout}\n{r.stderr}")
        if not mds:
            err = next((ln for ln in r.stdout.splitlines() if ln.startswith("ERR ")), "")
            expected[p.name] = {"rejected": True, "error": err}
            continue
        md = mds[0].read_text(encoding="utf-8")
        grade = re.search(r"\*\*제안 등급: (\w+)\*\*", md).group(1)
        reasons = [ln[2:] for ln in re.search(r"근거:\n((?:- .*\n)+)", md).group(1).strip().split("\n")]
        rec = re.findall(r"^\| (DEV-\d{4}-\d{4}) \| \d{4}-\d{2}-\d{2} \|", md, re.M)
        unchecked = "반복성 조회를 하지 않았습니다" in md
        expected[p.name] = {"rejected": False, "grade": grade, "reasons": reasons, "rec": rec, "recUnchecked": unchecked}

history = (REPO / "data/synthetic/history.csv").read_text(encoding="utf-8")
OUT = {
    "tests/fixtures/forms.json": json.dumps(forms, ensure_ascii=False, indent=1) + "\n",
    "tests/fixtures/cli_expected.json": json.dumps(expected, ensure_ascii=False, indent=1) + "\n",
}
template = {"own": _template_comments(), "phrases": _template_phrases()}
sample = ("// Generated by web/tools/make_fixtures.py from data/synthetic and templates/. Synthetic data only. Do not edit.\n"
          "export const SAMPLE_FORMS = " + json.dumps([f["form"] for f in forms], ensure_ascii=False).replace("<", "\\u003c") + ";\n"
          "export const SAMPLE_HISTORY = " + json.dumps(history, ensure_ascii=False).replace("<", "\\u003c") + ";\n"
          "// Guidance sentences of the blank intake template: a value that contains one swallowed a comment.\n"
          "export const TEMPLATE_COMMENTS = " + json.dumps(template, ensure_ascii=False).replace("<", "\\u003c") + ";\n")

# --- YAML: what the CLI reads from each text. web = "same" (must read the same) or "refuse" (outside the supported subset).
CASES = [
    ("plain and comments", "a: text  # note\nb: C# 코드\nc: 3.40-3.60\n# whole line\nd:    spaced   \n", "same"),
    ("numbers stay text", "batch: 0412\nstep: 1:30\nph: 3.40\nn: 12\nneg: -5\nexp: 1.5e3\nhex: 0x1F\ninf: .inf\n", "same"),
    ("booleans and empties", "t: true\nT: True\nF: FALSE\ny: yes\nn: no\non: on\nq: 'true'\ne:\nz: ~\nnu: null\ns: ''\n", "same"),
    ("dates stay text", "a: 2026-11-21T14:20\nb: 2026-11-21 14:20\nc: 2026-11-21\n", "same"),
    ("single quotes", "a: 'it''s'\nb: 'x # not a comment'   # comment\nc: 'a: b'\nd: ' padded '\n", "same"),
    ("double quotes", 'a: "say \\"hi\\""\nb: "tab\\there"\nc: "line\\nbreak"\nd: "u\\u00e9 x\\x41"\ne: "a: b # c"\n', "same"),
    ("quoted over lines", "a: 'first\n  second\n\n  third'\nb: \"one\n  two\\\n  three\"\nc: x\n", "same"),
    ("wrapped plain", "description: 용출 단계 pH가 3.62로 기록됨 (허용 범위 3.40-3.60). 이탈 시간 약 6분.\n  용출 완충액 lot BUF-5531\n  사용.\ntitle: x\n", "same"),
    ("wrapped plain with gap", "a: one\n  two\n\n  three\nb: y\n", "same"),
    ("value on next line", "a:\n  starts below\n  and wraps\nb: y\n", "same"),
    ("literal block", "description: |\n  line 1\n  line 2\n\n  # kept, not a comment\n    indented more\ntitle: x\n", "same"),
    ("literal strip and keep", "a: |-\n  no newline\nb: |+\n  keeps\n\nc: |\n  clip\n\n\nd: z\n", "same"),
    ("literal at end of file", "a: |\n  last\n", "same"),
    ("empty literal", "a: |\nb: x\n", "same"),
    ("parameters at column 0", "parameters:\n- name: Elution pH\n  spec: 3.40-3.60\n  actual: '3.62'\n  duration: 6 min\n- name: TOC\n  spec: ≤ 500 ppb\n  actual: 412 ppb\nx: y\n", "same"),
    ("parameters indented", "parameters:\n  - name: A   # c\n    spec: 1\n\n  - name: B\n    actual:\nx: y\n", "same"),
    ("empty list", "parameters: []\nx: y\n", "same"),
    ("document start, BOM, CRLF", "\ufeff---\r\na: 1\r\nb: |\r\n  two\r\n  lines\r\n", "same"),
    ("hash glued to value", "title: 제목# [필수] 한 줄 제목\n", "same"),
    ("colon inside plain value", "a: x: y\n", "same"),
    ("unclosed quote", "a: 'open\nb: x\n", "same"),
    ("text after quote", "a: 'x' y\n", "same"),
    ("tab indentation", "parameters:\n\t- name: A\n", "same"),
    ("bad indentation", "a: x\n   b: y\nc: z\n", "same"),
    ("not a mapping", "just text\n", "refuse"),
    ("duplicate key", "a: 1\na: 2\n", "refuse"),
    ("folded block", "a: >\n  one\n  two\n", "refuse"),
    ("nested mapping", "a:\n  b: c\n", "refuse"),
    ("flow list", "a: [1, 2]\n", "refuse"),
    ("flow map", "a: {b: c}\n", "refuse"),
    ("anchor and alias", "a: &x v\nb: *x\n", "refuse"),
    ("tag", "a: !!str 12\n", "refuse"),
    ("list of plain items", "parameters:\n- one\n- two\n", "refuse"),
    ("two documents", "a: 1\n---\nb: 2\n", "refuse"),
    ("block with indent digit", "a: |2\n    x\n", "refuse"),
]
for p in paths + sorted((REPO / "data/synthetic/tutorial").glob("*.yaml")) + [REPO / "templates/intake_template.yaml"]:
    CASES.append((p.name, p.read_text(encoding="utf-8"), "same"))
cases = []
for name, text, web in CASES:
    try:
        expect = {"value": form_load(text)}
    except yaml.YAMLError:
        expect = {"error": True}
    cases.append({"name": name, "text": text, "web": web, **expect})
OUT["tests/fixtures/yaml_cases.json"] = json.dumps(cases, ensure_ascii=False, indent=1) + "\n"
OUT["src/sample.js"] = sample
rules_path = REPO / "config/rules.yaml"
OUT["tests/fixtures/rules.json"] = json.dumps({"file": rules_path.name, "sha256": hashlib.sha256(rules_path.read_bytes()).hexdigest(),
                                               "rules": load_rules(rules_path)}, ensure_ascii=False, indent=1) + "\n"

stale = [name for name, text in OUT.items() if not (HERE / name).exists() or (HERE / name).read_text(encoding="utf-8") != text]
if CHECK:
    if stale:
        sys.exit("web 기준값이 지금 CLI 결과와 다름: " + ", ".join(stale) + " — python web/tools/make_fixtures.py 로 다시 만들고 web 테스트를 돌리십시오.")
    print(f"web fixtures are current ({len(OUT)} files)")
    sys.exit(0)
for name, text in OUT.items():
    (HERE / name).parent.mkdir(parents=True, exist_ok=True)
    (HERE / name).write_text(text, encoding="utf-8", newline="\n")
print(f"yaml cases: {len(cases)} ({sum(1 for c in cases if 'error' in c)} the CLI refuses, {sum(1 for c in cases if c['web'] == 'refuse')} only the web refuses)")
for name, e in expected.items():
    print(name, "REJECTED " + e["error"] if e["rejected"] else f"{e['grade']} rec={len(e['rec'])} unchecked={e['recUnchecked']}")
